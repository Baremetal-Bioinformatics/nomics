fn inv_gamma1pm1(x: f64) -> f64 {
    let t = if x <= 0.5 { x } else { (x - 0.5) - 0.5 };
    if t < 0.0 {
        let a = A[0] + t * A[1];
        let mut b = B[7];
        for i in (0..7).rev() {
            b = B[i] + t * b;
        }
        b = 1.0 + t * b;
        let mut c = C[13] + t * (a / b);
        for i in (1..13).rev() {
            c = C[i] + t * c;
        }
        c = -0.422784335098467139393487909917598 + t * c;
        if x > 0.5 {
            t * c / x
        } else {
            x * ((c + 0.5) + 0.5)
        }
    } else {
        let mut p = P[6];
        for i in (0..6).rev() {
            p = P[i] + t * p;
        }
        let mut q = Q[3];
        for i in (0..3).rev() {
            q = Q[i] + t * q;
        }
        q = 1.0 + t * q;
        let mut c = C[13] + (p / q) * t;
        for i in (0..13).rev() {
            c = C[i] + t * c;
        }
        if x > 0.5 {
            (t / x) * ((c - 0.5) - 0.5)
        } else {
            x * c
        }
    }
}
pub(crate) fn log_gamma1p(x: f64) -> f64 {
    -log1p(inv_gamma1pm1(x))
}
pub(crate) fn log_gamma(x: f64) -> f64 {
    if x.is_nan() || x <= 0.0 {
        return f64::NAN;
    }
    if x < 0.5 {
        return log_gamma1p(x) - log(x);
    }
    if x <= 2.5 {
        return log_gamma1p((x - 0.5) - 0.5);
    }
    if x <= 8.0 {
        let n = (x - 1.5).floor() as usize;
        let mut prod = 1.0;
        for i in 1..=n {
            prod *= x - i as f64;
        }
        return log_gamma1p(x - (n + 1) as f64) + log(prod);
    }
    let mut sum = 0.0;
    for i in (1..15).rev() {
        sum += LANCZOS[i] / (x + i as f64);
    }
    sum += LANCZOS[0];
    let tmp = x + 607.0 / 128.0 + 0.5;
    ((x + 0.5) * log(tmp)) - tmp + 0.5 * log(2.0 * std::f64::consts::PI) + log(sum / x)
}
pub(crate) fn gamma_small(x: f64) -> f64 {
    debug_assert!(x > 0.0 && x <= 20.0);
    if x >= 1.0 {
        let mut prod = 1.0;
        let mut t = x;
        while t > 2.5 {
            t -= 1.0;
            prod *= t;
        }
        prod / (1.0 + inv_gamma1pm1(t - 1.0))
    } else {
        1.0 / (x * (1.0 + inv_gamma1pm1(x)))
    }
}
pub(crate) fn digamma(x: f64) -> f64 {
    if x > 0.0 && x <= 1e-5 {
        return -0.577215664901532860606512090082 - 1.0 / x;
    }
    if x >= 49.0 {
        let inv = 1.0 / (x * x);
        return log(x) - 0.5 / x - inv * ((1.0 / 12.0) + inv * (1.0 / 120.0 - inv / 252.0));
    }
    digamma(x + 1.0) - 1.0 / x
}
